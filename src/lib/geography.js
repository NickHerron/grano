// The single source of truth for turning a free-text location string into structured
// city/state — used by both the admin backfill panel and, later, any form that wants
// it. Deliberately conservative: only returns confident:true when the string is
// unambiguously "City, ST" or "City, State Name" shaped. A bare "Chicago" or an
// ambiguous "Logan Square, Chicago" (same shape as "Chicago, Illinois" — only the
// state-name lookup tells them apart) comes back not-confident and is left for a
// human to fill in via the profile form — never guessed, never silently written.

import { slugify } from '@/lib/slugify'

// Census place/county names include non-ASCII characters (Puerto Rico: "Boquerón",
// "Añasco") that plain slugify() would mangle into garbage ("boquer-n") since its
// regex only keeps a-z0-9. NFD-normalizing and stripping combining marks first fixes
// that — and is a complete no-op for any ASCII input, so geoSlug('Chicago') is
// byte-identical to slugify('Chicago'). Existing entity slugs (built with plain
// slugify()) are never touched or regenerated by this.
const COMBINING_DIACRITICS = /[̀-ͯ]/g

export function geoSlug(text) {
  const stripped = text.normalize('NFD').replace(COMBINING_DIACRITICS, '')
  return slugify(stripped)
}

// Census's LSAD (Legal/Statistical Area Description) code, from the Gazetteer place
// file — distinguishes an incorporated city from a town/village/CDP/etc. Codes below
// are every value actually present in the 2024 national places file.
export const LSAD_LABELS = {
  '25': 'city',
  '43': 'town',
  '47': 'village',
  '21': 'borough',
  '57': 'CDP', // Census Designated Place — an unincorporated community, no local government
  '55': 'comunidad', // Puerto Rico
  '62': 'zona urbana', // Puerto Rico
  '35': 'metro township',
  '37': 'municipality',
  '53': 'city and borough',
  '00': 'balance',
  CG: 'consolidated government',
  CN: 'consolidated government',
  MG: 'metropolitan government',
  UC: 'unified government',
  UG: 'unified government',
}

export function lsadLabel(code) {
  return LSAD_LABELS[code] || 'place'
}

