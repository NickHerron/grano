const VALID_STATE_CODES = new Set(Object.values(usStateAbbreviations))
const STATE_NAME_BY_CODE = Object.fromEntries(Object.entries(usStateAbbreviations).map(([name, code]) => [code, name]))

// [code, "Title Case Name"] pairs, alphabetized by name — the one list every state
// <select> in the app renders from, so they can never drift apart.
export const US_STATE_OPTIONS = Object.entries(usStateAbbreviations)
  .map(([name, code]) => [code, name.replace(/\b\w/g, c => c.toUpperCase())])
  .sort((a, b) => a[1].localeCompare(b[1]))

// 'IL' -> 'Illinois', for display where a page wants the full name.
export function stateLabel(code) {
  const name = STATE_NAME_BY_CODE[code?.toUpperCase()]
  return name ? name.replace(/\b\w/g, c => c.toUpperCase()) : code
}

export function parseLocationString(raw) {
  if (!raw || typeof raw !== 'string') return { city: null, state: null, confident: false }
  const parts = raw.split(',').map(s => s.trim()).filter(Boolean)
  if (parts.length !== 2 || !parts[0] || !parts[1]) return { city: null, state: null, confident: false }

  const [city, statePart] = parts
  const upper = statePart.toUpperCase()
  if (VALID_STATE_CODES.has(upper)) return { city, state: upper, confident: true }

  const lower = statePart.toLowerCase()
  if (usStateAbbreviations[lower]) return { city, state: usStateAbbreviations[lower], confident: true }

  return { city: null, state: null, confident: false }
}
